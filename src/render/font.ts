// Vorsortierte Raster: GLYPH → 7×5-Boolean-Feld
const CACHE = new Map<string, boolean[][]>();

function glyphOf(ch: string): boolean[][] {
  const cached = CACHE.get(ch);
  if (cached) return cached;
  const raw = RAW[ch];
  if (!raw) return glyphOf('?');
  const grid: boolean[][] = [];
  for (let r = 0; r < 7; r++) {
    const row: boolean[] = [];
    for (let c = 0; c < 5; c++) {
      row.push((raw[r]?.[c] ?? '.') === '#');
    }
    grid.push(row);
  }
  CACHE.set(ch, grid);
  return grid;
}

export const FONT = Object.freeze({
  charW: 5,
  charH: 7,
  /** Gibt es das Zeichen im Font? */
  has(ch: string): boolean {
    return ch === ' ' || RAW[ch] !== undefined;
  },
});

/**
 * Zeichnet Text im 5×7-Pixel-Font. `pixel` = Größe eines Pixels in
 * Weltkoordinaten. Gibt die Breite in Weltkoordinaten zurück.
 */
export function drawPixelText(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  text: string,
  pixel: number,
  color?: string,
): number {
  ctx.save();
  ctx.fillStyle = color ?? fg();
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const grid = glyphOf(ch);
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (grid[r]![c]) {
          ctx.fillRect(cx + c * pixel, y + r * pixel, pixel, pixel);
        }
      }
    }
    cx += 6 * pixel; // 1 Pixel Abstand zwischen Zeichen
  }
  ctx.restore();
  return cx - x;
}

/** Textbreite im Pixel-Font. */
export function pixelTextWidth(text: string, pixel: number): number {
  return text.toUpperCase().length * 6 * pixel;
}